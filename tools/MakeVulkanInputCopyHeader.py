#!/usr/bin/env python3
"""Writes src/vulkan/VulkanInputCopy.h: the three input-copy compute shaders as SPIR-V words (standard library only).

The shaders are MFG-Unlocker's own vk_input_copy.comp (MIT, Copyright (c) 2026 Michael Robles), compiled by its generator
xess/vulkan/generate_vk_input_shaders.py. They resample the game's depth and motion vectors into XeFG's images, the part
of the Vulkan route that isn't one of the Intel derived programs, so they are built into the dll instead of read from
xefg_mfg_programs\\vulkan. The SPIR-V comes from a folder ExtractXeFgVulkanPrograms.py made from an MFGUnlocker.asi
(input_copy_0.spv, input_copy_1.spv, input_copy_2.spv) and has to be the one the generator pins.

    MakeVulkanInputCopyHeader.py DIR [-o src/vulkan/VulkanInputCopy.h]
"""
import argparse
import hashlib
import os
import struct
import sys

# Pinned by xess/vulkan/generate_vk_input_shaders.py, lower case
PINNED = (
    "f6f48f06d01134d9596b117e0c98b4a1a098325ab5b67268eedee8554955b7ca",  # 0 r32f (depth)
    "112a67e0df42b09edab40be77f505d58f5b2d3b357bda64a45f145fb247ce0d3",  # 1 rg16f (motion vectors)
    "2e34c018e32f1a5fd819e93e2e46cf31c454312c8d3f53ae22d491d2e1470fbc",  # 2 rg32f (motion vectors)
)

HEADER = """// The Vulkan route's input-copy compute shaders: MFG-Unlocker's own xess/vulkan/vk_input_copy.comp (MIT, Copyright (c)
// 2026 Michael Robles, see NOTICE.md), compiled by its generator xess/vulkan/generate_vk_input_shaders.py. Each one
// copies a depth or motion vector image of the game, point sampled, into the image XeFG reads, at the size XeFG needs.
//
// Generated by tools/MakeVulkanInputCopyHeader.py from the asi's own modules, don't edit. The SHA-256 of every module's
// bytes is pinned: variant 0 r32f (depth), 1 rg16f and 2 rg32f (motion vectors).
#pragma once

#include <cstddef>
#include <cstdint>

namespace VulkanInputCopy
{
"""


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.strip().split("\n\n")[0])
    parser.add_argument("directory", help="a folder made by ExtractXeFgVulkanPrograms.py")
    parser.add_argument("-o", "--output", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "vulkan",
                                                               "VulkanInputCopy.h"))
    args = parser.parse_args(argv[1:])

    lines = [HEADER.rstrip("\n"), ""]
    modules = []

    for index, pinned in enumerate(PINNED):
        path = os.path.join(args.directory, "input_copy_%d.spv" % index)
        with open(path, "rb") as file:
            raw = file.read()

        if hashlib.sha256(raw).hexdigest() != pinned:
            print("%s isn't the shader MFG-Unlocker's generator pins (%s)" % (path, hashlib.sha256(raw).hexdigest()),
                  file=sys.stderr)
            return 1

        if len(raw) % 4 or raw[:4] != b"\x03\x02\x23\x07":
            print("%s isn't a SPIR-V module" % path, file=sys.stderr)
            return 1

        words = struct.unpack("<%dI" % (len(raw) // 4), raw)
        modules.append(len(raw))

        lines.append("\tinline constexpr uint32_t Shader%d[] = {" % index)
        for at in range(0, len(words), 8):
            lines.append("\t\t" + ", ".join("0x%08x" % word for word in words[at:at + 8]) + ",")
        lines.append("\t};")
        lines.append("")

    lines.append("\tinline constexpr size_t Count = 3;")
    lines.append("\tinline constexpr const uint32_t* const Modules[Count] = { Shader0, Shader1, Shader2 };")
    lines.append("\tinline constexpr size_t Bytes[Count] = { sizeof(Shader0), sizeof(Shader1), sizeof(Shader2) };")
    lines.append("\t// SHA-256 of Modules[i]'s bytes, lower case hex")
    lines.append("\tinline constexpr const char* const Sha256[Count] = {")
    for pinned in PINNED:
        lines.append('\t\t"%s",' % pinned)
    lines.append("\t};")
    lines.append("} // namespace VulkanInputCopy")
    lines.append("")

    with open(args.output, "w", encoding="ascii", newline="\n") as file:
        file.write("\n".join(lines))

    print("wrote %s (%s bytes of SPIR-V)" % (os.path.normpath(args.output), ", ".join(str(n) for n in modules)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
